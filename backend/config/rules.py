# [이 파일이 하는 일]
#   공공와이파이 지점마다 '위험요인 점수(0~100점)'를 매기는데, 그 점수를 계산할 때 쓰는
#   모든 기준 숫자(가중치·임계값·등급 경계)를 한곳에 모아 둔 '설정표'입니다.
#
# [왜 한곳에 모았나]
#   점수 계산 코드 여기저기에 30, 20 같은 숫자를 직접 쓰면, 기준을 바꿀 때 한 군데를 빼먹기 쉽습니다.
#   그래서 숫자는 오직 여기서만 정하고, 다른 코드는 모두 이 파일을 불러다 씁니다.
#   화면에 내려가는 rules.json, 채점표, 가중치 슬라이더의 기본값도 전부 여기서 만들어집니다.
#
# [용어 풀이]
#   - AP(Access Point): 와이파이 신호를 내보내는 공유기 한 대.
#   - SSID: 휴대폰 와이파이 목록에 보이는 와이파이 이름. 예) "Public WiFi Free"
#   - R1~R8: 위험요인(Rule) 8가지. 각 요인마다 0~1 사이 '위험비율'을 구하고 가중치를 곱해 점수를 냅니다.
#   - 가중치(max_points): 그 위험요인이 100점 만점에서 차지하는 최대 점수.
#
# 원래 메모: 모든 가중치·파라미터는 여기서만 정의한다. rules.json, 채점표, 슬라이더 기본값이 모두 여기서 나온다.
# (plan.md §8.1) 점수 로직 어디에도 숫자(30, 20, …)를 직접 쓰지 않는다.
# ─────────────────────────────────────────────────────────────────────────────
from dataclasses import dataclass

# 화면(프론트엔드)과 백엔드가 주고받는 데이터 형식의 버전 번호가 적힌 파일 위치
CONTRACT_VERSION_FILE = "contracts/VERSION"

# 화면·문서 곳곳에 반드시 붙이는 안내 문구. 점수가 '해킹당할 확률'로 오해받지 않게 하기 위함.
DISCLAIMER = "이 점수는 실제 해킹 확률이 아니라 위험요인 지표입니다."


@dataclass(frozen=True)
class Rule:
    """위험요인 하나의 정보를 담는 상자(frozen=True: 한 번 만들면 값을 바꿀 수 없음).

    - id: 요인 번호 (예: "R1")
    - name: 사람이 읽는 이름 (예: "보안접속 미지원")
    - max_points: 기본 가중치 = 100점 중 이 요인이 차지하는 최대 점수
    - source_fields: 판정할 때 보는 원본 데이터 칸 이름들
    - is_assumption: True면 '근거 데이터가 약해 팀이 가정으로 정한 요인'이라는 표시
    - one_liner: 발표·화면용 한 줄 설명
    """
    id: str
    name: str
    max_points: int
    source_fields: tuple
    is_assumption: bool
    one_liner: str   # 발표 1줄 설명. 1줄로 못 쓰면 규칙 삭제(투명성 원칙)


# 위험요인 8가지 목록. 가중치를 모두 더하면 30+20+10+15+10+5+5+5 = 100점이 됩니다.
RULES = (
    Rule("R1", "보안접속 미지원", 30, ("ssid",), False,
         "SSID가 팀이 확정한 보안접속 목록에 없으면 위험요인으로 본다"),
    Rule("R2", "시설유형", 20, ("facility_type",), True,
         "불특정 다수가 오가는 시설일수록 높게 본다"),
    Rule("R3", "실외", 10, ("place_detail", "facility_type"), True,
         "설치장소 문구에 실외 키워드가 있으면 위험요인으로 본다"),
    Rule("R4", "노후도", 15, ("install_ym",), True,
         "설치 후 오래될수록 장비 보안 수준이 낮을 수 있다고 가정한다"),
    Rule("R5", "개방형 AP 밀집도", 10, ("lat", "lng", "ssid"), False,
         "반경 100m 안 개방형 AP가 많을수록 위장 AP가 섞이기 쉽다"),
    Rule("R6", "제공주체 불명", 5, ("provider", "manager"), False,
         "제공사·관리기관 정보가 비어 있으면 위험요인으로 본다"),
    Rule("R7", "신고경로 부재", 5, ("manager_tel",), False,
         "관리기관 전화번호가 없거나 형식이 틀리면 위험요인으로 본다"),
    Rule("R8", "데이터 노후", 5, ("data_date",), False,
         "데이터 기준일자가 오래되면 운영 상태를 신뢰하기 어렵다"),
)

# 위 목록에서 번호만 뽑은 것: ("R1", "R2", ..., "R8")
RULE_IDS = tuple(r.id for r in RULES)
# 위 목록에서 기본 가중치만 뽑은 것: (30, 20, 10, 15, 10, 5, 5, 5)
DEFAULT_WEIGHTS = tuple(r.max_points for r in RULES)

